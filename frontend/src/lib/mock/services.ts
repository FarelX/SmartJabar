// Helper: get top N services by usage_count
export function getTopServices(services: Service[], n: number = 3): Service[] {
  return [...services]
    .filter(s => s.is_active)
    .sort((a, b) => (b.usage_count ?? 0) - (a.usage_count ?? 0))
    .slice(0, n)
}
